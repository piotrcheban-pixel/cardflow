/// Результат повторного поиска картинки карточки (итерация 7.14).
///
/// Домен не знает о сети/UI: сервис (`CardImageRefresher`) возвращает код,
/// экран показывает строку ARB.
library;

/// Итог повторного поиска.
enum CardImageRefreshResult {
  /// Картинка найдена и сохранена.
  updated,

  /// Картинку не нашли/не скачали — остаётся прежняя (заглушка).
  notFound,

  /// Нет сохранённого запроса модели — искать не по чему.
  noQuery,

  /// Медиа не найдено в БД.
  missing,
}
