ПРАВИЛА КАЧЕСТВА КАРТОЧЕК
Правило 1. Атомарность: один факт = одна карточка
Каждая карточка проверяет РОВНО ОДИН факт, понятие, формулу или связь.
Если ответ содержит перечисление из нескольких независимых элементов или союз «и» между двумя самостоятельными утверждениями — разбей на несколько карточек.
Исключение: неделимые наборы (например, «три закона Ньютона» как перечень названий) допустимы, но лучше сделать отдельную карточку на каждый элемент.
Не дублируй карточки: один и тот же факт не должен проверяться дважды с разными формулировками.
Не создавай карточки по оглавлению, колонтитулам, номерам страниц, подписям «Рис. N», ссылкам и служебным данным.

Правило 2. Вопрос (front) НЕ содержит ответа
front — это вопрос или задание, которое заставляет ВСПОМНИТЬ или ПРИМЕНИТЬ знание. Он никогда не содержит то, что проверяется.
ЗАПРЕЩЕНО: помещать в front формулу, определение, термин или значение, которые являются ответом.
ЗАПРЕЩЕНО: формулировать front как утверждение или заголовок («Формула момента силы», «Первый закон Ньютона»).
ЗАПРЕЩЕНЫ вопросы с ответом «да/нет» и вопросы, на которые можно ответить, просто перефразировав вопрос.
Предпочитай вопросы на понимание: «Как найти…?», «Чему равен…?», «Почему…?», «Что произойдёт, если…?», «Чем отличается X от Y?», «Какая величина…?», «При каком условии…?».
front должен быть однозначным: на него существует один правильный ответ, совпадающий с back. Добавляй необходимый контекст (раздел, условия), но не подсказку.
Примеры:
ПЛОХО: front: «Формула момента силы $M_z = x F_y - y F_x$» — ответ уже в вопросе.
ХОРОШО: front: «Как вычислить момент силы $\vec{F}$ относительно оси $z$ через её проекции и координаты точки приложения?» → back: «$M_z = x F_y - y F_x$».
ПЛОХО: front: «Аксиома статики о равновесии двух сил: две силы уравновешены, если равны и противоположны».
ХОРОШО: front: «При каком условии две силы, приложенные к абсолютно твёрдому телу, уравновешивают друг друга?» → back: «Когда они равны по модулю и направлены противоположно вдоль одной прямой».
ПЛОХО: front: «Формула геометрической неизменяемости плоской фермы $s = 2n - 3$» → back: «$s$ — число стержней, $n$ — число узлов» — ответ в вопросе, а back лишь расшифровывает буквы.
ХОРОШО: front: «Каким соотношением должны быть связаны число стержней $s$ и число узлов $n$, чтобы плоская ферма была геометрически неизменяемой и статически определимой?» → back: «$s = 2n - 3$».
ПЛОХО: front: «Является ли митохондрия органоидом клетки?» (да/нет).
ХОРОШО: front: «Какой органоид клетки обеспечивает синтез АТФ при клеточном дыхании?» → back: «Митохондрия».

Правило 3. Ответ (back) краткий
back — 1–2 предложения, максимум ~200 символов. Для термина или формулы допустим ответ из одного слова или одной формулы.
Только суть, без вводных фраз («Ответ:», «Как известно…», «Следует отметить…»), без повторения вопроса.
Если для ответа нужно больше двух предложений — карточка не атомарна, разбей её.

Правило 4. Форматирование и LaTeX
В front, back и hint ЗАПРЕЩЁН любой Markdown: никаких **, *, _ для выделения, #, списков, таблиц, обратных кавычек, ссылок, HTML-тегов.
Любая математика, формулы, переменные, индексы, единицы в формулах, греческие буквы — ТОЛЬКО внутри LaTeX-разделителей:
$...$ — inline-формула внутри текста;
$$...$$ — отдельная (блочная) формула, если она длинная или является всем ответом.
ЗАПРЕЩЕНЫ другие разделители: \(...\), \[...\], \begin{equation}, а также формулы без разделителей.
ЗАПРЕЩЕНО писать математику обычным текстом или Unicode: не «Mz = x*Fy», не «F₁», не «α», не «√2», а $M_z = x F_y$, $F_1$, $\alpha$, $\sqrt{2}$.
Символ $ не используй как знак валюты (пиши «руб.», «долл.»).
Каждый открытый $ или $$ обязательно закрыт. Внутри разделителей — только корректный LaTeX: многосимвольные индексы и степени в фигурных скобках ($x_{max}$, $e^{-kt}$), функции через команды ($\sin \alpha$, $\ln x$), умножение через \cdot или пробел, не через *. Текст внутри формулы — через \text{...}.
Не оборачивай в LaTeX обычные слова и числа, не являющиеся частью формулы.
JSON-экранирование: каждый обратный слэш LaTeX в строке JSON удваивается. Пиши "$\\frac{a}{b}$", "$\\vec{F}$", "$\\alpha$". Одиночный \ внутри JSON-строки запрещён.

Правило 5. Тип карточки (card_type)
basic — вопрос-ответ. Используй по умолчанию.
basic_reversed — двусторонняя, только если обе стороны осмысленны как вопрос (термин ↔ определение, дата ↔ событие, формула ↔ название величины).
cloze — предложение с пропуском: в front разметка {{c1::пропущенный текст}}, при нескольких пропусках {{c1::…}}, {{c2::…}} по порядку. Пропускается ключевой факт, а не служебное слово. back для cloze — краткое пояснение или пустая строка "".

Правило 6. Подсказка, теги, источник
hint — короткая подсказка, которая наводит на ответ, но не раскрывает его и не повторяет вопрос; если подсказка не нужна — null.
tags — 1–3 тега по содержанию, строчными буквами, без символа #.
source_excerpt — дословная цитата из materials (1–3 предложения, от 15 до 400 символов), на которой основана карточка; она должна буквально встречаться в тексте. Если materials пуст или цитату выделить нельзя — null.
source_file — имя файла из строки «Файл: <имя>», откуда взята карточка. Если materials пуст или файл неясен — null.

Правило 7. Изображения: image_id и image_query
Изображение добавляй, только если оно прямо помогает вспомнить именно этот ответ. По умолчанию оба поля — null. Лучше без картинки, чем с неподходящей.
Приоритет 1 — изображения из прикреплённых файлов. Если в <images> есть изображение, которое по подписи и окружающему тексту прямо иллюстрирует вопрос или ответ (схема, рисунок, чертёж, график из материала), укажи его id в image_id. Используй только id из <images>, никогда не выдумывай id и URL. Если указан image_id, image_query = null.
Приоритет 2 — внешний поиск (image_query), только если подходящего изображения в <images> нет.
Ищи картинку ТОЛЬКО для конкретных физических объектов, которые можно сфотографировать или изобразить узнаваемо: мост, животное, растение, орган, конкретный прибор или механизм, деталь, минерал, историческое здание, географический объект.
Для абстрактных понятий — аксиома, закон, теорема, формула, определение, свойство, принцип, дата, классификация, правило — image_query ОБЯЗАН быть null.
Перед заполнением спроси себя: «Поможет ли изображение именно этого объекта вспомнить именно этот ответ?» Если нет или сомневаешься — null.
Если ищешь, запрос:
на английском языке, 3–7 слов;
описывает конкретный объект, а не тему;
содержит дисциплинарный контекст и тип изображения, например: "physics free body diagram inclined plane", "truss bridge structure engineering", "mitochondria cell organelle diagram", "vernier caliper measuring instrument".
ЗАПРЕЩЕНЫ общие или случайные запросы, связанные с вопросом лишь по ассоциации (например, "ball" для аксиомы статики, "apple" для закона всемирного тяготения, "book", "science", "formula").

